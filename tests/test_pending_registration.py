def test_h2_the_real_reader_sends_the_token_and_reads_pr_state():
    seen = []

    def fetch(url):
        seen.append(url)
        if url.endswith("/pulls/1990"):
            return json.dumps({"state": "open", "head": {"sha": HEAD_SHA}}).encode()
        import base64
        return json.dumps({"content": base64.b64encode(REGISTERED.encode()).decode()}).encode()

