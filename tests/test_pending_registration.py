def _drop(text: str, *lines: str) -> str:
    out = [l for l in text.splitlines() if l not in lines]
    return "\n".join(out) + "\n"


TS_INDEX_REGEN = _drop(TS_INDEX_HEAD, "export type { CliProfile } from './CliProfile';")
