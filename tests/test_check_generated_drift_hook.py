"""End-to-end tests: the real `check-generated-drift.sh --verify` with pending registrations.

Plan: 2026-10-13-schemas-check-drift-red-while-bindings-await-runner-registration

Each test builds a throwaway git repo laid out as `qontinui-schemas/`, commits a
synthetic baseline, then edits the working tree the way a regeneration would.
`GENERATE_TYPES_SH` points at tests/fixtures/drift_hook/generate_types.sh, a stub
that passes the gate's generator cross-check, so a red can only come from the
arm under test. GitHub is replaced by the module's one test seam,
PENDING_REGISTRATION_FIXTURE. No network, no runner checkout.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
STUB_GENERATOR = REPO / "tests" / "fixtures" / "drift_hook" / "generate_types.sh"
HEAD_SHA = "aa63c83cce0184d8cf6ac1d5aac50c181de38e4c"
TODAY = dt.datetime.now(dt.timezone.utc).date()

pytestmark = pytest.mark.skipif(shutil.which("bash") is None or shutil.which("git") is None,
                                reason="needs bash and git")

TS_INDEX = (
    "// Auto-generated by compile_typescript.mjs — do not edit\n"
    "export type { A11yAction } from './A11yAction';\n"
    "export type { CliProfile } from './CliProfile';\n"
)
PY_INIT = (
    "# Auto-generated by generate_types.sh — do not edit\n"
    "from .per_type.a11y_action import A11yAction\n"
    "from .per_type.cli_profile import CliProfile\n"
    "__all__ = [\n"
    '    "A11yAction",\n'
    '    "CliProfile",\n'
    "]\n"
)
TIMESTAMPED = "#   timestamp: {ts}\nclass T{i}:\n    x = {i}\n"
N_TIMESTAMPED = 5


def git(root: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(root), *args], check=True,
                          capture_output=True, text=True).stdout.strip()


def write(root: Path, rel: str, text: str) -> None:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


def toml_entry(added: dt.date = TODAY) -> str:
    return (
        "# header\n"
        "[[pending]]\n"
        'type = "CliProfile"\n'
        'runner_pr = "qontinui/qontinui-runner#1990"\n'
        f"added = {added.isoformat()}\n"
        'schemas_pr = "qontinui/qontinui-schemas#212"\n'
    )


def make_repo(tmp_path: Path, toml: str | None, with_cli_profile: bool = True) -> Path:
    root = tmp_path / "qontinui-schemas"
    root.mkdir()
    git(root, "init", "-q")
    git(root, "config", "user.email", "t@example.invalid")
    git(root, "config", "user.name", "t")
    for name in ("check-generated-drift.sh", "pending_registration.py"):
        write(root, f"scripts/{name}", (REPO / "scripts" / name).read_text(encoding="utf-8"))
    write(root, "ts/src/generated/A11yAction.d.ts", "export type A11yAction = 'a';\n")
    write(root, "src/qontinui_schemas/generated/per_type/a11y_action.py", "class A11yAction: ...\n")
    for i in range(N_TIMESTAMPED):
        write(root, f"src/qontinui_schemas/generated/per_type/t{i}.py",
              TIMESTAMPED.format(ts="2026-10-10T00:00:00", i=i))
    if with_cli_profile:
        write(root, "ts/src/generated/CliProfile.d.ts", "export interface CliProfile {}\n")
        write(root, "src/qontinui_schemas/generated/per_type/cli_profile.py", "class CliProfile: ...\n")
        write(root, "ts/src/generated/index.ts", TS_INDEX)
        write(root, "src/qontinui_schemas/generated/__init__.py", PY_INIT)
    else:
        write(root, "ts/src/generated/index.ts", TS_INDEX.replace("export type { CliProfile } from './CliProfile';\n", ""))
        write(root, "src/qontinui_schemas/generated/__init__.py",
              PY_INIT.replace("from .per_type.cli_profile import CliProfile\n", "").replace('    "CliProfile",\n', ""))
    if toml is not None:
        write(root, "codegen/pending-registration.toml", toml)
    git(root, "add", "-A")
    git(root, "commit", "-qm", "baseline")
    return root


def regenerate_without_cli_profile(root: Path) -> None:
    """What a regeneration against runner main does to the pending type."""
    (root / "ts/src/generated/CliProfile.d.ts").unlink()
    (root / "src/qontinui_schemas/generated/per_type/cli_profile.py").unlink()
    write(root, "ts/src/generated/index.ts",
          TS_INDEX.replace("export type { CliProfile } from './CliProfile';\n", ""))
    write(root, "src/qontinui_schemas/generated/__init__.py",
          PY_INIT.replace("from .per_type.cli_profile import CliProfile\n", "").replace('    "CliProfile",\n', ""))
    for i in range(N_TIMESTAMPED):  # every regeneration rewrites the timestamp header
        write(root, f"src/qontinui_schemas/generated/per_type/t{i}.py",
              TIMESTAMPED.format(ts="2026-10-13T09:09:09", i=i))


def merge_pr_into(root: Path, base: str) -> str:
    """What a pull_request run checks out: the PR (HEAD) merged into `base`.

    Leaves HEAD at the merge commit, parents [base, PR head]; returns the PR head.
    """
    head = git(root, "rev-parse", "HEAD")
    git(root, "checkout", "-q", "--detach", base)
    git(root, "merge", "-q", "--no-ff", "--no-edit", head)
    return head


def fixture_file(tmp_path: Path, state: str = "open", text: str | None = None) -> Path:
    f = tmp_path / "github.json"
    f.write_text(json.dumps({"prs": {"qontinui/qontinui-runner#1990": {
        "state": state, "head_sha": HEAD_SHA,
        "schema_export": text if text is not None else 'fn x() { add!(\n "CliProfile",\n qcs::CliProfile); }',
    }}}))
    return f


def verify(root: Path, fixture: Path | None, path_prefix: Path | None = None,
           **env_extra: str) -> subprocess.CompletedProcess:
    env = {k: v for k, v in os.environ.items()
           if k not in ("GITHUB_WORKFLOW", "GITHUB_ACTIONS", "GITHUB_STEP_SUMMARY", "GITHUB_TOKEN",
                        "SIBLING_SOURCE", "SIBLING_SHA", "PR_HEAD_SHA", "PR_CREATED_AT", "PR_NUMBER",
                        "PENDING_REGISTRATION_FIXTURE")}
    env.update(GENERATE_TYPES_SH=str(STUB_GENERATOR), QONTINUI_SCHEMAS_DIR=str(root),
               SIBLING_SOURCE="none")
    if fixture is not None:
        env["PENDING_REGISTRATION_FIXTURE"] = str(fixture)
    if path_prefix is not None:
        env["PATH"] = f"{path_prefix}{os.pathsep}{env['PATH']}"
    env.update(env_extra)
    return subprocess.run(["bash", "scripts/check-generated-drift.sh", "--verify"], cwd=root,
                          env=env, capture_output=True, text=True)


def errors(out: str) -> list[str]:
    return [l for l in out.splitlines() if "::error::" in l]


